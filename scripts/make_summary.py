            x = m[split]["metrics"]
            h = x["headline"]["ci95"]
            L.append(f"| {lab} | {ci(x['ICD10CM'])} | {ci(x['SNOMEDCT_US'])} | **{h['headline']}** [{h['lo']}, {h['hi']}] |")
