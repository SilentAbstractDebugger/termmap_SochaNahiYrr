        ("Abbreviations / misspellings / OCR / truncation", "PARTIAL", "PARTIAL", f"OCR glyph views + noise augmentation; noisy slice ICD {v['ICD10CM'].get('noisy_oov_terms')}, SNOMED {v['SNOMEDCT_US'].get('noisy_oov_terms')}"),
        ("Context disambiguation", "PARTIAL", "PARTIAL", "context-vs-candidate char cosine + origin qualifier; hard cases ms/ra/pid in hard_cases.json"),
        ("Specificity calibration", "PARTIAL", "PARTIAL", f"learned unspecified/depth priors; over/under {v['ICD10CM']['over_coding_rate']}/{v['ICD10CM']['under_coding_rate']}"),
        ("No crosswalk collapse", "MET", "MET", "stage-2 uses the other system's description TEXT agreement as evidence only"),
        ("Long tail (unseen codes)", "PARTIAL", "PARTIAL", f"code-disjoint ICD {cdm['ICD10CM']['ci95']['acc']}, SNOMED {cdm['SNOMEDCT_US']['ci95']['acc']}"),
        ("FM7 version drift (incl. dense artifacts)", "MET", "MET", "EmbeddingStore re-embeds only new strings; test_dense_incremental_reembedding_on_drift"),
        ("Determinism (two-run identical hashes)", "MET", "MET" if det.get("identical") else "NOT MET", "reports/determinism.json; GPU stages cache embeddings/CE scores (not verified on GPU here)"),
        ("One command, offline, CPU fallback, mode printed", "MET", "MET", "termmap.predict; test_fallback_modes"),
        ("Measurement hygiene: seeds, bootstrap CIs, FINAL TEST", "NOT MET", "MET", "scripts/train.py; reports/metrics.json"),
        ("Dense biomedical encoder benchmark", "NOT MET", "NOT MET", "NOT RUN: no GPU/HF; scripts/dense_benchmark.py + kaggle_run.sh"),
        ("gte-base top-1 diagnostic", "NOT MET", "NOT MET", "NOT RUN (dense_benchmark.py computes it on Kaggle)"),
        ("Fine-tuned encoder", "NOT MET", "NOT MET", "code + leakage test; NOT RUN for accuracy"),
        ("Cross-encoder reranker", "NOT MET", "NOT MET", "code + OOF tables + features + tests; NOT RUN for accuracy"),
        ("Calibration + routing", "PARTIAL", "MET" if "ece_uncalibrated" in v["ICD10CM"] else "PARTIAL",
         f"ECE {v['ICD10CM'].get('ece_uncalibrated', v['ICD10CM']['ece'])} -> {v['ICD10CM']['ece']} (ICD val); route_for_review in diagnostics"),
        ("LLM adjudication", "NOT MET", "NOT MET", "not run (optional)"),
        ("External resources named with licences", "PARTIAL", "MET", "spaCy en_core_web_lg licence MIT (vectors CC0) read from packaged meta.json; HF model licences recorded at download"),
