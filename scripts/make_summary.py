"""reports/SUMMARY.md: measured numbers (with CIs) + requirement traceability (iteration 2)."""
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from termmap.util import ROOT, read_json  # noqa: E402


def j(name, default=None):
    p = ROOT / "reports" / name
    return read_json(p) if p.exists() else default


def tests():
    p = ROOT / "reports" / "pytest.xml"
    if not p.exists():
        return {"summary": "not run", "failed": []}
    r = ET.parse(p).getroot()
    ts = r if r.tag == "testsuite" else r.find("testsuite")
    n, f, e, s = (int(ts.get(k, 0)) for k in ("tests", "failures", "errors", "skipped"))
    failed = [tc.get("name") for tc in ts.iter("testcase") if tc.find("failure") is not None or tc.find("error") is not None]
    return {"summary": f"{n - f - e - s}/{n} passed, {f} failed, {e} errors, {s} skipped", "failed": failed}


def ci(x):
    c = x["ci95"]
    return f"{c['acc']} [{c['lo']}, {c['hi']}] (n={c['n']})"


def main():
    m, base = j("metrics.json"), j("baseline_iter2.json")
    bm, det, hc = j("benchmark.json", {}), j("determinism.json", {}), j("hard_cases.json", [])
    ea = j("error_analysis_val.json", {})
    t = tests()
    L = ["# TermMap - summary, iteration 2 (all numbers measured; generated by scripts/make_summary.py)", "",
         "Environment of this iteration: CPU only (2 cores), **no GPU, no Hugging Face access** -> biomedical dense "
         "encoders, fine-tuning and cross-encoder were implemented and mechanically tested but NOT RUN for accuracy.", ""]
